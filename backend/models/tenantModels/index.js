import guestHouseSchema from './GuestHouse.js';
import roomSchema from './Room.js';
import bedSchema from './Bed.js';
import bookingSchema from './Booking.js';
import userSchema from './User.js';
import taxSchema from './Tax.js';
import paymentSchema from './Payment.js';
import invoiceSchema from './Invoice.js';
import auditLogSchema from './AuditLog.js';
import counterSchema from './Counter.js';
import configurationSchema from './Configuration.js';
import dynamicPricingSchema from './DynamicPricing.js';
import bedConfigSchema from './BedConfig.js';
import itemSchema from './Item.js';
import inventorySchema from './Inventory.js';
import itemRequestSchema from './ItemRequest.js';
import itemIssueSchema from './ItemIssue.js';
import banquetHallSchema from './BanquetHall.js';
import banquetOccupancySchema from './BanquetOccupancy.js';
import banquetEnquirySchema from './BanquetEnquiry.js';
import banquetQuotationSchema from './BanquetQuotation.js';

export default function initTenantModels(conn) {
  if (!conn.models.GuestHouse)     conn.model('GuestHouse', guestHouseSchema);
  if (!conn.models.Room)           conn.model('Room', roomSchema);
  if (!conn.models.Bed)            conn.model('Bed', bedSchema);
  if (!conn.models.Booking)        conn.model('Booking', bookingSchema);
  if (!conn.models.User)           conn.model('User', userSchema);
  if (!conn.models.Tax)            conn.model('Tax', taxSchema);
  if (!conn.models.Payment)        conn.model('Payment', paymentSchema);
  if (!conn.models.Invoice)        conn.model('Invoice', invoiceSchema);
  if (!conn.models.AuditLog)       conn.model('AuditLog', auditLogSchema);
  if (!conn.models.Counter)        conn.model('Counter', counterSchema);
  if (!conn.models.Configuration)  conn.model('Configuration', configurationSchema);
  if (!conn.models.DynamicPricing) conn.model('DynamicPricing', dynamicPricingSchema);
  if (!conn.models.BedConfig)      conn.model('BedConfig', bedConfigSchema);
  if (!conn.models.Item)           conn.model('Item', itemSchema);
  if (!conn.models.Inventory)      conn.model('Inventory', inventorySchema);
  if (!conn.models.ItemRequest)    conn.model('ItemRequest', itemRequestSchema);
  if (!conn.models.ItemIssue)      conn.model('ItemIssue', itemIssueSchema);
  if (!conn.models.BanquetHall)     conn.model('BanquetHall', banquetHallSchema);
  if (!conn.models.BanquetOccupancy) conn.model('BanquetOccupancy', banquetOccupancySchema);
  if (!conn.models.BanquetEnquiry) conn.model('BanquetEnquiry', banquetEnquirySchema);
  if (!conn.models.BanquetQuotation) conn.model('BanquetQuotation', banquetQuotationSchema);
}
